# Większe / mniejsze
print(5 > 4) # True
print(5 < 4) # False
print(5 > 5) # False

# Większe lub równe / mniejsze lub równe
print(5 >= 5) # True
print(5 <= 5) # True

# Nierówne (różne)
print(5 != 5) # False
print(5 != 4) # True

# Równe
print(5 == 5) # True
print(5 == 4) # False
print(5 == 2 + 3) # True
print('test' == 'test') # True
print('test' == 'test2') # False