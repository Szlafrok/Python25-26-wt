dzien = int(input())

if dzien == 1:
    print("poniedziałek")
elif dzien == 2:
    print("wtorek")
elif dzien == 3:
    print("środa")
elif dzien == 4:
    print("czwartek")
elif dzien == 5:
    print("piątek")
elif dzien == 6:
    print("sobota")
else:
    print("niedziela")


