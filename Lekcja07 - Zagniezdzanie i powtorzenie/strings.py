tekst = "MANAAM"
tekst2 = "umpalumpas"
tekst3 = "AmperCola123"


# upper
print(tekst.upper())
print(tekst2.upper())
print(tekst3.upper())

# lower
print(tekst.lower())
print(tekst2.lower())
print(tekst3.lower())

# isupper
print(tekst.isupper()) # tak
print(tekst2.isupper()) # nie
print(tekst3.isupper()) # nie

# islower
print(tekst.islower()) # nie
print(tekst2.islower()) # tak
print(tekst3.islower()) # nie